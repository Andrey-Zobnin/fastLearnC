#include <stdio.h>

// переменная - изменяемые значения
// константы и литералы - неизменяемые значения
// в один мбайт можно записать числа в диапазоне от нуля до 255
// <тип переменной> <имя переменной>; - синтаксис задания переменной



int main() {
    char byteMemory;
    // char - ключевое слово, byteMemory - идентификатор
    byteMemory = 100;
    char a;
    a = byteMemory;
    printf("Hello, world!\n");
    return 0;
}